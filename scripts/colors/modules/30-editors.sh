#!/usr/bin/env bash
set -euo pipefail

source "$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)/lib/module-runtime.sh"
COLOR_MODULE_ID="editors"

SCSS_FILE="$STATE_DIR/user/generated/material_colors.scss"
APP_PALETTE_FILE="$STATE_DIR/user/generated/app-palette.json"
PALETTE_FILE="$STATE_DIR/user/generated/palette.json"
TERMINAL_FILE="$STATE_DIR/user/generated/terminal.json"
LEGACY_COLORS_FILE="$STATE_DIR/user/generated/colors.json"
REPO_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"
VSCODE_THEMEGEN_BIN="$STATE_DIR/user/generated/bin/alis-vscode-themegen"
OPENCODE_THEMEGEN_BIN="$STATE_DIR/user/generated/bin/alis-opencode-themegen"
NEOVIM_CONFIG_DIR="$XDG_CONFIG_HOME/nvim"
NEOVIM_PLUGIN_DIR="$NEOVIM_CONFIG_DIR/lua/plugins"
NEOVIM_THEME_FILE="$NEOVIM_PLUGIN_DIR/neovim.lua"
NEOVIM_ALIS_COLOR_ALIAS="$NEOVIM_CONFIG_DIR/colors/alis.lua"
NEOVIM_OMARCHY_OVERRIDE_FILE="$NEOVIM_PLUGIN_DIR/zz-alis-omarchy.lua"
NEOVIM_LEGACY_OMARCHY_OVERRIDE_FILE="$NEOVIM_PLUGIN_DIR/zz-inir-omarchy.lua"
NEOVIM_THEMEGEN="$SCRIPT_DIR/neovim_themegen.sh"
NEOVIM_BUNDLED_PLUGIN_INIT="$SCRIPT_DIR/neovim/plugin/lua/alis/init.lua"
NEOVIM_LOCAL_PLUGIN_DIR="$STATE_DIR/user/generated/alis.nvim"

EDITORS_THEME_LOG="$STATE_DIR/user/generated/code_editor_themes.log"
EDITORS_INPUT_SIG_FILE="$STATE_DIR/user/generated/.editors-themegen-input.sig"

ensure_vscode_themegen() {
  command -v go &>/dev/null || return 1
  mkdir -p "$STATE_DIR/user/generated/bin"
  if [[ ! -x "$VSCODE_THEMEGEN_BIN" || "$REPO_ROOT/go.mod" -nt "$VSCODE_THEMEGEN_BIN" || "$SCRIPT_DIR/vscode_themegen/main.go" -nt "$VSCODE_THEMEGEN_BIN" || "$SCRIPT_DIR/themegencommon/common.go" -nt "$VSCODE_THEMEGEN_BIN" ]]; then
    (cd "$REPO_ROOT" && go build -o "$VSCODE_THEMEGEN_BIN" ./scripts/colors/vscode_themegen) >/dev/null 2>&1 || return 1
  fi
  [[ -x "$VSCODE_THEMEGEN_BIN" ]]
}

ensure_opencode_themegen() {
  command -v go &>/dev/null || return 1
  mkdir -p "$STATE_DIR/user/generated/bin"
  if [[ ! -x "$OPENCODE_THEMEGEN_BIN" || "$REPO_ROOT/go.mod" -nt "$OPENCODE_THEMEGEN_BIN" || "$SCRIPT_DIR/opencode_themegen/main.go" -nt "$OPENCODE_THEMEGEN_BIN" || "$SCRIPT_DIR/themegencommon/common.go" -nt "$OPENCODE_THEMEGEN_BIN" ]]; then
    (cd "$REPO_ROOT" && go build -o "$OPENCODE_THEMEGEN_BIN" ./scripts/colors/opencode_themegen) >/dev/null 2>&1 || return 1
  fi
  [[ -x "$OPENCODE_THEMEGEN_BIN" ]]
}

generate_neovim_spec() {
  local colors_file="$1"
  bash "$NEOVIM_THEMEGEN" "$colors_file" "$TERMINAL_FILE" "$NEOVIM_PLUGIN_DIR"
}

is_managed_neovim_file() {
  local file="$1"
  [[ -f "$file" ]] || return 1
  head -n 5 "$file" | grep -Eq 'auto-generated by (Alis|iNiR)|Auto-generated by (Alis|iNiR)'
}

# Remove generated neovim spec when theming is disabled.
# Only deletes files proven to carry the Alis/iNiR generator header; never
# deletes a manually customized neovim.lua solely because it mentions a plugin.
strip_neovim_spec() {
  local candidate
  local lazy_root="${NVIM_LAZY_ROOT:-${XDG_DATA_HOME:-$HOME/.local/share}/nvim/lazy}"
  for candidate in \
    "$NEOVIM_THEME_FILE" \
    "$NEOVIM_ALIS_COLOR_ALIAS" \
    "$NEOVIM_OMARCHY_OVERRIDE_FILE" \
    "$NEOVIM_LEGACY_OMARCHY_OVERRIDE_FILE"; do
    if is_managed_neovim_file "$candidate"; then
      rm -f "$candidate"
    fi
  done
  rm -rf "$NEOVIM_LOCAL_PLUGIN_DIR" "$lazy_root/alis.nvim.cloning"
}

is_antigravity_present() {
  [[ -d "$XDG_CONFIG_HOME/Antigravity" ]] \
    || [[ -d "$XDG_CONFIG_HOME/Antigravity IDE" ]] \
    || [[ -d "$HOME/.antigravity" ]] \
    || [[ -d "$HOME/.antigravity-ide" ]] \
    || [[ -f "$HOME/.local/share/applications/alis-app-antigravity.desktop" ]] \
    || [[ -f "$HOME/.local/share/applications/alis-app-antigravity-ide.desktop" ]] \
    || command -v antigravity >/dev/null 2>&1 \
    || command -v antigravity-ide >/dev/null 2>&1
}

build_editors_input_signature() {
  local colors_file="$1" config_flags="$2" targets_state="$3"
  {
    printf 'flags:%s\ntargets:%s\n' "$config_flags" "$targets_state"
    # A desktop app can be installed or its settings changed after a palette was
    # generated. Include target settings and generator sources in the cache key.
    for file in "$SCSS_FILE" "$colors_file" "$TERMINAL_FILE" \
      "${BASH_SOURCE[0]}" "$NEOVIM_THEMEGEN" "$NEOVIM_BUNDLED_PLUGIN_INIT" \
      "$SCRIPT_DIR/desktop_ai_themes.py" \
      "$REPO_ROOT/native/alis-theme/src/editors.rs" \
      "$SCRIPT_DIR/codex/theme_generator.py" "$SCRIPT_DIR/claude/theme_generator.py" \
      "$SCRIPT_DIR/vscode/theme_generator.py" "$SCRIPT_DIR/vscode_themegen/main.go" \
      "${codex_dir:-$HOME/.codex}/config.toml" \
      "${claude_dir:-$HOME/.claude}/settings.json" \
      "${claude_desktop_dir:-$XDG_CONFIG_HOME/Claude}/config.json" \
      "$HOME/.gemini/config/config.json"; do
      if [[ -f "$file" ]]; then
        cksum "$file"
      else
        printf 'missing:%s\n' "$file"
      fi
    done
    for file in "$XDG_CONFIG_HOME/Codex" "$XDG_CONFIG_HOME/ChatGPT"; do
      if [[ -d "$file" ]]; then
        printf 'desktop:%s\n' "$file"
      fi
    done
  } | cksum | awk '{print $1 ":" $2}'
}

apply_code_editors() {
  [[ -f "$SCSS_FILE" ]] || return 0
  local colors_file="$APP_PALETTE_FILE"
  [[ -f "$colors_file" ]] || colors_file="$PALETTE_FILE"
  [[ -f "$colors_file" ]] || colors_file="$LEGACY_COLORS_FILE"

  # Batch all config reads into a single jq invocation to avoid spawning ~18 jq processes
  local enable_vscode="true" enable_neovim="false" enable_opencode="false" enable_codex="true" enable_claude="true"
  local f_code="true" f_codium="true" f_codeOss="true" f_codeInsiders="true" f_cursor="true"
  local f_windsurf="true" f_windsurfNext="true" f_qoder="true" f_antigravity="true" f_positron="true"
  local f_voidEditor="true" f_melty="true" f_pearai="true" f_aide="true"

  if [[ -f "$CONFIG_FILE" ]] && command -v jq >/dev/null 2>&1; then
    local jq_out
    jq_out=$(jq -r '
      (.appearance.wallpaperTheming // {}) as $wt |
      ($wt.vscodeEditors // {}) as $ve |
      def b($obj; $k; $def): if ($obj | type) == "object" and ($obj | has($k)) then ($obj[$k] | tostring) else $def end;
      [
        b($wt; "enableVSCode"; "true"),
        b($wt; "enableNeovim"; "false"),
        b($wt; "enableOpenCode"; "false"),
        b($wt; "enableCodex"; "true"),
        b($wt; "enableClaude"; "true"),
        b($ve; "code"; "true"),
        b($ve; "codium"; "true"),
        b($ve; "codeOss"; "true"),
        b($ve; "codeInsiders"; "true"),
        b($ve; "cursor"; "true"),
        b($ve; "windsurf"; "true"),
        b($ve; "windsurfNext"; "true"),
        b($ve; "qoder"; "true"),
        b($ve; "antigravity"; "true"),
        b($ve; "positron"; "true"),
        b($ve; "voidEditor"; "true"),
        b($ve; "melty"; "true"),
        b($ve; "pearai"; "true"),
        b($ve; "aide"; "true")
      ] | @tsv
    ' "$CONFIG_FILE" 2>/dev/null || true)
    if [[ -n "$jq_out" ]]; then
      IFS=$'\t' read -r \
        enable_vscode enable_neovim enable_opencode enable_codex enable_claude \
        f_code f_codium f_codeOss f_codeInsiders f_cursor \
        f_windsurf f_windsurfNext f_qoder f_antigravity f_positron \
        f_voidEditor f_melty f_pearai f_aide <<< "$jq_out"
    fi
  fi

  local enabled_forks=()
  local disabled_forks=()
  if [[ "$enable_vscode" == 'true' ]]; then
    _add_fork() {
      local flag="$1" fork_key="$2" config_dir="$3" always_include="${4:-false}"
      if [[ "$always_include" != "true" && ! -d "$config_dir" ]]; then
        return 0
      fi
      if [[ "$flag" == "true" ]]; then
        enabled_forks+=("$fork_key")
      else
        disabled_forks+=("$fork_key")
      fi
    }

    _add_fork "$f_code" code "$XDG_CONFIG_HOME/Code" true
    _add_fork "$f_codium" codium "$XDG_CONFIG_HOME/VSCodium" true
    _add_fork "$f_codeOss" code-oss "$XDG_CONFIG_HOME/Code - OSS"
    _add_fork "$f_codeInsiders" code-insiders "$XDG_CONFIG_HOME/Code - Insiders"
    _add_fork "$f_cursor" cursor "$XDG_CONFIG_HOME/Cursor"
    _add_fork "$f_windsurf" windsurf "$XDG_CONFIG_HOME/Windsurf"
    _add_fork "$f_windsurfNext" windsurf-next "$XDG_CONFIG_HOME/Windsurf - Next"
    _add_fork "$f_qoder" qoder "$XDG_CONFIG_HOME/Qoder"
    if is_antigravity_present; then
      _add_fork "$f_antigravity" antigravity "$XDG_CONFIG_HOME/Antigravity" true
    else
      _add_fork "$f_antigravity" antigravity "$XDG_CONFIG_HOME/Antigravity"
    fi
    _add_fork "$f_positron" positron "$XDG_CONFIG_HOME/Positron"
    _add_fork "$f_voidEditor" void "$XDG_CONFIG_HOME/Void"
    _add_fork "$f_melty" melty "$XDG_CONFIG_HOME/Melty"
    _add_fork "$f_pearai" pearai "$XDG_CONFIG_HOME/PearAI"
    _add_fork "$f_aide" aide "$XDG_CONFIG_HOME/Aide"
    unset -f _add_fork
  fi

  local codex_dir="${CODEX_HOME:-$HOME/.codex}"
  if [[ -z "${CODEX_HOME:-}" && ! -d "$codex_dir" && -d "$XDG_CONFIG_HOME/codex" ]]; then
    codex_dir="$XDG_CONFIG_HOME/codex"
  fi
  local claude_dir="${CLAUDE_CONFIG_DIR:-$HOME/.claude}"
  local claude_desktop_dir="${CLAUDE_DESKTOP_CONFIG_DIR:-$XDG_CONFIG_HOME/Claude}"

  local targets_state=""
  for fk in "${enabled_forks[@]}"; do
    local ext_theme="$HOME/.${fk}/extensions/alis-material-theme/themes/alis-material-color-theme.json"
    [[ "$fk" == "code" ]] && ext_theme="$HOME/.vscode/extensions/alis-material-theme/themes/alis-material-color-theme.json"
    [[ "$fk" == "codium" || "$fk" == "code-oss" ]] && ext_theme="$HOME/.vscode-oss/extensions/alis-material-theme/themes/alis-material-color-theme.json"
    [[ "$fk" == "antigravity" && ! -f "$ext_theme" && -f "$HOME/.antigravity-ide/extensions/alis-material-theme/themes/alis-material-color-theme.json" ]] && ext_theme="$HOME/.antigravity-ide/extensions/alis-material-theme/themes/alis-material-color-theme.json"
    [[ -f "$ext_theme" ]] && targets_state+="v:${fk}:1," || targets_state+="v:${fk}:0,"
  done
  [[ -f "$codex_dir/themes/alis.tmTheme" ]] && targets_state+="codex:1," || targets_state+="codex:0,"
  [[ -f "$claude_dir/themes/alis.json" ]] && targets_state+="claude:1," || targets_state+="claude:0,"
  if [[ -f "$NEOVIM_THEME_FILE" ]]; then
    if ! is_managed_neovim_file "$NEOVIM_THEME_FILE"; then
      targets_state+="nvim:user,"
    elif [[ -f "$NEOVIM_LOCAL_PLUGIN_DIR/lua/alis/init.lua" ]] && ! grep -Fq '"yukazakiri/alis.nvim"' "$NEOVIM_THEME_FILE" 2>/dev/null; then
      targets_state+="nvim:1,"
    else
      targets_state+="nvim:0,"
    fi
  else
    targets_state+="nvim:0,"
  fi

  local config_flags="${enable_vscode}:${enable_neovim}:${enable_opencode}:${enable_codex}:${enable_claude}:${enabled_forks[*]}:${disabled_forks[*]}"
  local input_sig
  input_sig="$(build_editors_input_signature "$colors_file" "$config_flags" "$targets_state")"
  if [[ -f "$EDITORS_INPUT_SIG_FILE" ]] && [[ "$(cat "$EDITORS_INPUT_SIG_FILE" 2>/dev/null || true)" == "$input_sig" ]]; then
    return 0
  fi

  mkdir -p "$STATE_DIR/user/generated"
  local pids=()

  # 1. Neovim
  (
    if [[ "$enable_neovim" == 'true' ]] && [[ -d "$NEOVIM_CONFIG_DIR" || -x "$(command -v nvim 2>/dev/null)" ]]; then
      generate_neovim_spec "$colors_file"
    else
      strip_neovim_spec
    fi
  ) &
  pids+=("$!")

  # 2. VSCode & Forks (including Antigravity)
  (
    if [[ "$enable_vscode" == 'true' ]]; then
      if [[ ${#enabled_forks[@]} -gt 0 ]]; then
        local vscode_args=("--colors" "$colors_file" "--terminal-json" "$TERMINAL_FILE" "--scss" "$SCSS_FILE")
        for fork in "${enabled_forks[@]}"; do
          vscode_args+=("--forks" "$fork")
        done
        if "$REPO_ROOT/scripts/native-dispatch" vscode-theme "${vscode_args[@]}" >> "$EDITORS_THEME_LOG" 2>&1; then
          :
        elif ensure_vscode_themegen; then
          "$VSCODE_THEMEGEN_BIN" "${vscode_args[@]}" >> "$EDITORS_THEME_LOG" 2>&1 || true
        else
          local python_cmd
          python_cmd=$(venv_python)
          "$python_cmd" "$SCRIPT_DIR/generate_terminal_configs.py" --scss "$SCSS_FILE" --colors "$colors_file" --terminal-json "$TERMINAL_FILE" --vscode --vscode-forks "${enabled_forks[@]}" >> "$EDITORS_THEME_LOG" 2>&1 || true
        fi
      fi

      if [[ ${#disabled_forks[@]} -gt 0 ]]; then
        local strip_args=("--strip")
        for fork in "${disabled_forks[@]}"; do
          strip_args+=("--forks" "$fork")
        done
        if "$REPO_ROOT/scripts/native-dispatch" vscode-theme "${strip_args[@]}" >> "$EDITORS_THEME_LOG" 2>&1; then
          :
        elif ensure_vscode_themegen; then
          "$VSCODE_THEMEGEN_BIN" "${strip_args[@]}" >> "$EDITORS_THEME_LOG" 2>&1 || true
        else
          local python_cmd
          python_cmd=$(venv_python)
          "$python_cmd" "$SCRIPT_DIR/vscode/theme_generator.py" --strip --forks "${disabled_forks[@]}" >> "$EDITORS_THEME_LOG" 2>&1 || true
        fi
      fi
    else
      if "$REPO_ROOT/scripts/native-dispatch" vscode-theme --strip >> "$EDITORS_THEME_LOG" 2>&1; then
        :
      elif ensure_vscode_themegen; then
        "$VSCODE_THEMEGEN_BIN" --strip >> "$EDITORS_THEME_LOG" 2>&1 || true
      else
        local python_cmd
        python_cmd=$(venv_python)
        "$python_cmd" "$SCRIPT_DIR/vscode/theme_generator.py" --strip >> "$EDITORS_THEME_LOG" 2>&1 || true
      fi
    fi
  ) &
  pids+=("$!")

  # 3. OpenCode
  (
    if [[ "$enable_opencode" == 'true' ]] && command -v opencode &>/dev/null; then
      if "$REPO_ROOT/scripts/native-dispatch" opencode-theme "$SCSS_FILE" "$colors_file" "$TERMINAL_FILE" >> "$EDITORS_THEME_LOG" 2>&1; then
        :
      elif ensure_opencode_themegen; then
        "$OPENCODE_THEMEGEN_BIN" "$SCSS_FILE" "$colors_file" "$TERMINAL_FILE" >> "$EDITORS_THEME_LOG" 2>&1 || true
      else
        local python_cmd
        python_cmd=$(venv_python)
        "$python_cmd" "$SCRIPT_DIR/opencode/theme_generator.py" "$SCSS_FILE" "$colors_file" "$TERMINAL_FILE" >> "$EDITORS_THEME_LOG" 2>&1 || true
      fi
    fi
  ) &
  pids+=("$!")

  # 4. OpenAI Codex CLI
  (
    if [[ "$enable_codex" == 'true' ]]; then
      if command -v codex &>/dev/null || [[ -d "$codex_dir" ]]; then
        "$REPO_ROOT/scripts/native-dispatch" codex-theme \
          --colors "$colors_file" \
          --terminal-json "$TERMINAL_FILE" \
          --scss "$SCSS_FILE" >> "$EDITORS_THEME_LOG" 2>&1
      fi
    else
      if [[ -f "$codex_dir/themes/alis.tmTheme" || -f "$STATE_DIR/user/generated/codex_prev_theme.txt" ]]; then
        "$REPO_ROOT/scripts/native-dispatch" codex-theme --strip >> "$EDITORS_THEME_LOG" 2>&1
      fi
    fi
  ) &
  pids+=("$!")

  # 5. Claude Code CLI & Claude Desktop
  (
    if [[ "$enable_claude" == 'true' ]]; then
      if command -v claude &>/dev/null || command -v claude-desktop &>/dev/null || [[ -d "$claude_dir" ]] || [[ -d "$claude_desktop_dir" ]]; then
        "$REPO_ROOT/scripts/native-dispatch" claude-theme \
          --colors "$colors_file" \
          --terminal-json "$TERMINAL_FILE" \
          --scss "$SCSS_FILE" >> "$EDITORS_THEME_LOG" 2>&1
      fi
    else
      if [[ -f "$claude_dir/themes/alis.json" || -f "$STATE_DIR/user/generated/claude_prev_theme.txt" || -f "$STATE_DIR/user/generated/claude_desktop_prev_theme.txt" || -f "$STATE_DIR/user/generated/claude_prev_theme.json" || -f "$STATE_DIR/user/generated/claude_desktop_prev_theme.json" ]]; then
        "$REPO_ROOT/scripts/native-dispatch" claude-theme --strip >> "$EDITORS_THEME_LOG" 2>&1
      fi
    fi
  ) &
  pids+=("$!")

  local editors_failed="false"
  for pid in "${pids[@]}"; do
    if ! wait "$pid"; then
      editors_failed="true"
    fi
  done

  # Codex desktop and Antigravity App use their own supported settings stores;
  # CLI themes and VSCode extensions cannot change those applications.
  local desktop_python desktop_antigravity="false"
  desktop_python="$(venv_python)"
  [[ "$enable_vscode" == 'true' && "$f_antigravity" == 'true' ]] && desktop_antigravity="true"
  if ! "$desktop_python" "$SCRIPT_DIR/desktop_ai_themes.py" \
    --colors "$colors_file" --codex "$enable_codex" --antigravity "$desktop_antigravity" \
    >> "$EDITORS_THEME_LOG" 2>&1; then
    log_module "desktop AI theme settings failed; leaving signature uncached for retry"
    return 1
  fi
  if [[ "$editors_failed" == "true" ]]; then
    log_module "editor theme generation failed; leaving signature uncached for retry"
    return 1
  fi

  # Recompute signature after outputs are populated so subsequent identical runs fast-skip
  targets_state=""
  for fk in "${enabled_forks[@]}"; do
    local ext_theme="$HOME/.${fk}/extensions/alis-material-theme/themes/alis-material-color-theme.json"
    [[ "$fk" == "code" ]] && ext_theme="$HOME/.vscode/extensions/alis-material-theme/themes/alis-material-color-theme.json"
    [[ "$fk" == "codium" || "$fk" == "code-oss" ]] && ext_theme="$HOME/.vscode-oss/extensions/alis-material-theme/themes/alis-material-color-theme.json"
    [[ "$fk" == "antigravity" && ! -f "$ext_theme" && -f "$HOME/.antigravity-ide/extensions/alis-material-theme/themes/alis-material-color-theme.json" ]] && ext_theme="$HOME/.antigravity-ide/extensions/alis-material-theme/themes/alis-material-color-theme.json"
    [[ -f "$ext_theme" ]] && targets_state+="v:${fk}:1," || targets_state+="v:${fk}:0,"
  done
  [[ -f "$codex_dir/themes/alis.tmTheme" ]] && targets_state+="codex:1," || targets_state+="codex:0,"
  [[ -f "$claude_dir/themes/alis.json" ]] && targets_state+="claude:1," || targets_state+="claude:0,"
  if [[ -f "$NEOVIM_THEME_FILE" ]]; then
    if ! is_managed_neovim_file "$NEOVIM_THEME_FILE"; then
      targets_state+="nvim:user,"
    elif [[ -f "$NEOVIM_LOCAL_PLUGIN_DIR/lua/alis/init.lua" ]] && ! grep -Fq '"yukazakiri/alis.nvim"' "$NEOVIM_THEME_FILE" 2>/dev/null; then
      targets_state+="nvim:1,"
    else
      targets_state+="nvim:0,"
    fi
  else
    targets_state+="nvim:0,"
  fi

  input_sig="$(build_editors_input_signature "$colors_file" "$config_flags" "$targets_state")"
  printf '%s\n' "$input_sig" > "$EDITORS_INPUT_SIG_FILE" 2>/dev/null || true
}

main() {
  apply_code_editors
}

main "$@"
