#!/usr/bin/env bash
# neovim_themegen.sh — writes the LazyVim plugin spec for yukazakiri/alis.nvim
# (external upstream plugin repository) with Alis compatibility aliases.
# The plugin itself handles all colour fetching, highlights, and live reload.
#
# Usage: neovim_themegen.sh <palette.json> <terminal.json> <plugin_dir>
set -euo pipefail

PALETTE_FILE="${1:?Usage: $0 <palette.json> <terminal.json> <plugin_dir>}"
TERMINAL_FILE="${2:?}"
NEOVIM_PLUGIN_DIR="${3:?}"

NEOVIM_CONFIG_DIR="$(dirname "$(dirname "$NEOVIM_PLUGIN_DIR")")"
NEOVIM_THEME_FILE="$NEOVIM_PLUGIN_DIR/neovim.lua"
NEOVIM_COLORS_DIR="$NEOVIM_CONFIG_DIR/colors"
NEOVIM_ALIS_COLOR_ALIAS="$NEOVIM_COLORS_DIR/alis.lua"
NEOVIM_LOCK_FILE="$NEOVIM_CONFIG_DIR/lazy-lock.json"
NEOVIM_OMARCHY_THEME_FILE="$NEOVIM_PLUGIN_DIR/theme.lua"
NEOVIM_OMARCHY_OVERRIDE_FILE="$NEOVIM_PLUGIN_DIR/zz-alis-omarchy.lua"
NEOVIM_LEGACY_OMARCHY_OVERRIDE_FILE="$NEOVIM_PLUGIN_DIR/zz-alis-omarchy.lua"
BACKUP_DIR="$(dirname "$PALETTE_FILE")/backups"

is_managed_neovim_file() {
  local file="$1"
  [[ -f "$file" ]] || return 1
  head -n 5 "$file" | grep -Eq 'auto-generated by (Alis|Alis)|Auto-generated by (Alis|Alis)'
}

backup_once() {
  local src="$1" name="$2"
  [[ -f "$src" ]] || return 0
  mkdir -p "$BACKUP_DIR"
  if [[ ! -f "$BACKUP_DIR/$name" ]]; then
    cp -p "$src" "$BACKUP_DIR/$name"
  fi
}

# Write file only if changed
write_if_changed() {
  local target="$1" tmp="${1}.tmp"
  cat > "$tmp"
  if [[ -f "$target" ]] && cmp -s "$tmp" "$target"; then
    rm -f "$tmp"
  else
    mv "$tmp" "$target"
    printf '[neovim_themegen] %s updated\n' "$(basename "$target")"
  fi
}

is_omarchy_theme_link() {
  [[ -L "$NEOVIM_OMARCHY_THEME_FILE" ]] || return 1

  local target
  target="$(readlink "$NEOVIM_OMARCHY_THEME_FILE" 2>/dev/null || true)"
  case "$target" in
    */omarchy/current/theme/neovim.lua) return 0 ;;
    *) return 1 ;;
  esac
}

mkdir -p "$NEOVIM_PLUGIN_DIR"

# Never overwrite a user-maintained neovim.lua that lacks our generator marker.
if [[ -f "$NEOVIM_THEME_FILE" ]] && ! is_managed_neovim_file "$NEOVIM_THEME_FILE"; then
  printf '[neovim_themegen] preserving user-owned %s\n' "$NEOVIM_THEME_FILE"
  exit 0
fi

if [[ -f "$NEOVIM_THEME_FILE" ]] && {
  grep -Fq '"yukazakiri/alis.nvim"' "$NEOVIM_THEME_FILE" ||
  grep -Fq 'auto-generated by Alis' "$NEOVIM_THEME_FILE"
}; then
  backup_once "$NEOVIM_THEME_FILE" "neovim.lua.pre-nvim01.bak"
fi

write_if_changed "$NEOVIM_THEME_FILE" <<'PLUGEOF'
-- neovim.lua — auto-generated by Alis. Use 99-alis-user.lua for overrides.
package.preload["alis"] = package.preload["alis"] or function()
  return require("alis")
end
return {
  {
    "yukazakiri/alis.nvim",
    priority = 1000,
    opts = {},
  },
  {
    "LazyVim/LazyVim",
    opts = {
      colorscheme = "alis",
    },
  },
}
PLUGEOF

# Provide a lightweight :colorscheme alis entrypoint that delegates to alis.nvim
# unless the user already maintains a custom colors/alis.lua file.
mkdir -p "$NEOVIM_COLORS_DIR"
if [[ ! -f "$NEOVIM_ALIS_COLOR_ALIAS" ]] || is_managed_neovim_file "$NEOVIM_ALIS_COLOR_ALIAS"; then
  write_if_changed "$NEOVIM_ALIS_COLOR_ALIAS" <<'COLOREOF'
-- colors/alis.lua — auto-generated by Alis.
require("alis").load()
COLOREOF
fi

# Reconcile lazy-lock.json if a broken alis.nvim lock entry exists or if
# alis.nvim is already installed locally in lazy/alis.nvim.
if [[ -f "$NEOVIM_LOCK_FILE" ]] && command -v python3 >/dev/null 2>&1; then
  lazy_root="${NVIM_LAZY_ROOT:-${XDG_DATA_HOME:-$HOME/.local/share}/nvim/lazy}"
  alis_lazy_dir="$lazy_root/alis.nvim"
  alis_commit=""
  alis_branch="main"
  if [[ -d "$alis_lazy_dir/.git" || -f "$alis_lazy_dir/.git" ]]; then
    alis_commit="$(git -C "$alis_lazy_dir" rev-parse HEAD 2>/dev/null || true)"
    b="$(git -C "$alis_lazy_dir" rev-parse --abbrev-ref HEAD 2>/dev/null || true)"
    [[ -n "$b" && "$b" != "HEAD" ]] && alis_branch="$b"
  fi
  python3 - "$NEOVIM_LOCK_FILE" "$BACKUP_DIR" "$alis_branch" "$alis_commit" <<'PY'
import json
from pathlib import Path
import shutil
import sys

lock_path = Path(sys.argv[1])
backup_dir = Path(sys.argv[2])
branch = sys.argv[3] or "main"
commit = sys.argv[4]

try:
    raw = lock_path.read_text(encoding="utf-8")
    data = json.loads(raw)
except Exception:
    raise SystemExit(0)

if not isinstance(data, dict):
    raise SystemExit(0)

changed = False
alis_entry = data.pop("alis.nvim", None)
if alis_entry is not None:
    changed = True
    if "alis.nvim" not in data and isinstance(alis_entry, dict) and alis_entry.get("commit"):
        data["alis.nvim"] = alis_entry

if "alis.nvim" not in data and commit:
    data["alis.nvim"] = {"branch": branch, "commit": commit}
    changed = True

if changed:
    backup_dir.mkdir(parents=True, exist_ok=True)
    bak = backup_dir / "lazy-lock.json.pre-nvim01.bak"
    if not bak.exists():
        shutil.copy2(lock_path, bak)
    lines = ["{"]
    keys = sorted(data.keys())
    for idx, k in enumerate(keys):
        v = data[k]
        comma = "," if idx + 1 < len(keys) else ""
        if isinstance(v, dict) and set(v.keys()) == {"branch", "commit"}:
            lines.append(
                f'  {json.dumps(k)}: {{ "branch": {json.dumps(v["branch"])}, "commit": {json.dumps(v["commit"])} }}{comma}'
            )
        else:
            lines.append(f"  {json.dumps(k)}: {json.dumps(v)}{comma}")
    lines.append("}\n")
    lock_path.write_text("\n".join(lines), encoding="utf-8")
PY
fi

# Omarchy installs a theme.lua symlink after this file alphabetically. Its
# aether spec would otherwise override Alis and its LazyReload handler would
# switch back to aether whenever the Omarchy theme changes.
if is_omarchy_theme_link; then
  if [[ ! -f "$NEOVIM_OMARCHY_OVERRIDE_FILE" ]] || is_managed_neovim_file "$NEOVIM_OMARCHY_OVERRIDE_FILE"; then
    write_if_changed "$NEOVIM_OMARCHY_OVERRIDE_FILE" <<'OVEREOF'
-- zz-alis-omarchy.lua — auto-generated by Alis.
-- Keep Alis authoritative while Neovim wallpaper theming is enabled.
return {
  {
    "bjarneo/aether.nvim",
    enabled = false,
  },
  {
    name = "theme-hotreload",
    dir = vim.fn.stdpath("config"),
    enabled = false,
  },
  {
    "LazyVim/LazyVim",
    opts = {
      colorscheme = "alis",
    },
  },
}
OVEREOF
  fi
elif is_managed_neovim_file "$NEOVIM_OMARCHY_OVERRIDE_FILE"; then
  rm -f "$NEOVIM_OMARCHY_OVERRIDE_FILE"
  printf '[neovim_themegen] removed stale: %s\n' "$(basename "$NEOVIM_OMARCHY_OVERRIDE_FILE")"
fi

if is_managed_neovim_file "$NEOVIM_LEGACY_OMARCHY_OVERRIDE_FILE"; then
  rm -f "$NEOVIM_LEGACY_OMARCHY_OVERRIDE_FILE"
  printf '[neovim_themegen] removed stale: %s\n' "$(basename "$NEOVIM_LEGACY_OMARCHY_OVERRIDE_FILE")"
fi

# Clean up stale files from previous versions only if they are not user-owned
for stale in \
  "$NEOVIM_PLUGIN_DIR/alis-colorscheme.lua" \
  "$NEOVIM_PLUGIN_DIR/alis_theme.lua" \
  "$NEOVIM_PLUGIN_DIR/alis-colorscheme.lua" \
  "$NEOVIM_PLUGIN_DIR/alis_theme.lua"
do
  if [[ -f "$stale" ]]; then
    rm -f "$stale"
    printf '[neovim_themegen] removed stale: %s\n' "$(basename "$stale")"
  fi
done
