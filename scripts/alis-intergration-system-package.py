def digest(data):
    return hashlib.sha256(data).hexdigest()


def run(command, *, cwd=None, timeout=15, input_bytes=None):
    try:
        if input_bytes is not None:
            return subprocess.run(command, cwd=cwd, input=input_bytes,
                                  capture_output=True, timeout=timeout, check=False)
        return subprocess.run(command, cwd=cwd, capture_output=True, text=True,
                              timeout=timeout, check=False)
    except (FileNotFoundError, subprocess.TimeoutExpired) as error:
        raise ValueError("Gateway package tool unavailable or timed out: " + command[0]) from error


def _parse_os_release(root=Path("/")):
    fields = {}
    for rel in ("etc/os-release", "usr/lib/os-release"):
        candidate = root / rel
        if candidate.is_file() and not candidate.is_symlink():
            for raw_line in candidate.read_text(encoding="utf-8", errors="replace").splitlines():
                line = raw_line.strip()
                if not line or line.startswith("#") or "=" not in line:
                    continue
                key, value = line.split("=", 1)
                fields[key.strip().lower()] = value.strip().strip('"').strip("'").lower()
            break
    return fields


def detect_distro(root=Path("/")):
    """Identify the host distribution family or fail closed on unsupported/immutable systems."""
    info = _parse_os_release(root)
    distro_id = info.get("id", "")
    id_like = set(info.get("id_like", "").split())
    variant_id = info.get("variant_id", "")
    tokens = {distro_id, variant_id} | id_like

    if (root / "etc/NIXOS").exists() or "nixos" in tokens:
        return {
            "family": "nixos",
            "supported": False,
            "packageManager": "nix",
            "diagnostic": "declarative-distro-manual",
            "reason": "NixOS uses declarative system configuration; declare the Polkit gateway in configuration.nix instead of imperative package installation",
        }
    if tokens & IMMUTABLE_VARIANTS or any(x in info.get("pretty_name", "") for x in ("silverblue", "kinoite", "microos")):
        return {
            "family": "immutable",
            "supported": False,
            "packageManager": "rpm-ostree",
            "diagnostic": "immutable-distro-unsupported",
            "reason": "Immutable/atomic root filesystem detected; refusing imperative /usr gateway package mutation",
        }
    if (root / "etc/arch-release").is_file() or "arch" in tokens or distro_id in {"cachyos", "endeavouros", "manjaro", "garuda", "artix"}:
        return {"family": "arch", "supported": True, "packageManager": "pacman", "diagnostic": "supported"}
    if (root / "etc/debian_version").is_file() or bool(tokens & {"debian", "ubuntu"}) or distro_id in {"pop", "linuxmint", "mint", "elementary", "zorin", "kali", "mx", "devuan"}:
        return {"family": "debian", "supported": True, "packageManager": "dpkg", "diagnostic": "supported"}
    if bool(tokens & {"opensuse", "suse"}) or (root / "etc/SuSE-release").is_file() or distro_id.startswith("opensuse"):
        return {"family": "opensuse", "supported": True, "packageManager": "rpm", "diagnostic": "supported"}
    if (root / "etc/fedora-release").is_file() or "fedora" in tokens or distro_id in {"nobara", "ultramarine"}:
        return {"family": "fedora", "supported": True, "packageManager": "rpm", "diagnostic": "supported"}
    return {
        "family": distro_id or "unknown",
        "supported": False,
        "packageManager": "unknown",
        "diagnostic": "unsupported-distro",
        "reason": f"Distribution '{distro_id or 'unknown'}' is not in the audited system gateway matrix (arch, debian, fedora, opensuse)",
    }


def installed(name, *, distro="arch", command=run):
    if distro == "arch":
        return command(["/usr/bin/pacman", "-Qq", name]).returncode == 0
    if distro == "debian":
        res = command(["/usr/bin/dpkg-query", "-W", "-f=${db:Status-Status}", name])
        return res.returncode == 0 and res.stdout.strip() == "installed"
    if distro in ("fedora", "opensuse"):
        return command(["/usr/bin/rpm", "-q", name]).returncode == 0
    return False


def expected_files(root):
    out = {}
    for name, (dest, sha, mode) in FILES.items():
        path = root / name
        if path.is_symlink() or not path.is_file():
            raise ValueError("Missing or linked trusted Alis source: " + name)
        content = path.read_bytes()
        if digest(content) != sha:
            raise ValueError("Alis system gateway source hash mismatch: " + name)
        out[dest] = (content, mode, sha)
    return out


def _files_match(root, specs):
    for destination, expected in specs:
        path = root / destination
        if path.is_symlink() or not path.is_file() or digest(path.read_bytes()) != expected:
            return False
    return True


def system_state(root=Path("/"), package_checker=None, *, distro=None, command=run):
    # Inspect the exact packaged destinations; do not use an unbound dict key.
    # Crucially this runs AFTER a successful privileged package install and must
    # return a receipt instead of crashing after a completed privileged action.
    detected = detect_distro(root) if distro is None else {
        "family": distro,
        "supported": distro in SUPPORTED_DISTROS,
        "packageManager": SUPPORTED_DISTROS.get(distro, {}).get("packageManager", "unknown"),
        "diagnostic": "supported" if distro in SUPPORTED_DISTROS else "unsupported-distro",
    }
    family = detected["family"]
    if package_checker is None:
        if not detected["supported"]:
            return {
                "packageInstalled": False,
                "sourcePackageAvailable": False,
                "installed": False,
                "distro": family,
                "packageManager": detected["packageManager"],
                "diagnostic": detected["diagnostic"],
            }
        checker = lambda pkg: installed(pkg, distro=family, command=command)
    else:
        checker = package_checker

    hashes = _files_match(root, ((dest, sha) for dest, sha, _ in FILES.values()))
    owned = checker(PACKAGE)
    if not owned and not hashes:
        legacy_hashes = _files_match(root, LEGACY_FILES)
        if legacy_hashes and checker(LEGACY_PACKAGE):
            owned = True
            hashes = True
    return {
        "packageInstalled": owned,
        "sourcePackageAvailable": bool(detected["supported"]),
        "installed": owned and hashes,
        "distro": family,
        "packageManager": detected["packageManager"],
        "diagnostic": "ready" if owned and hashes else "modified" if owned else "not-installed",
    }


def build_package(root, directory, command=run, extract=None):
    """Build and verify an Arch pacman gateway package as an unprivileged user."""
    payload = expected_files(root)
    path = Path(directory)
    stage = path / "payload"
    stage.mkdir(exist_ok=True)
    for dest, (content, mode, _) in payload.items():
        target = stage / Path(dest).name
        target.write_bytes(content)
        target.chmod(mode)
    (path / "PKGBUILD").write_text(PKGBUILD, encoding="utf-8")
    result = command(["/usr/bin/makepkg", "--force", "--noconfirm"], cwd=path, timeout=180)
    if result.returncode != 0:
        raise ValueError("makepkg could not build the trusted gateway: " + result.stderr[-MAX_RESULT:])
    packages = list(path.glob(PACKAGE + "-*.pkg.tar.*"))
    if len(packages) != 1:
        raise ValueError("Gateway build produced an unexpected package count")
    pkg = packages[0]
    names = command(["/usr/bin/bsdtar", "-tf", str(pkg)], timeout=30)
    if names.returncode != 0:
        raise ValueError("Cannot inspect the newly built gateway package")
    allowed = set(METADATA) | set(payload)
    for name in names.stdout.splitlines():
        normalized = name.removeprefix("./").rstrip("/")
        if not normalized:
            continue
        if normalized not in allowed and not any(
                x.startswith(normalized + "/") for x in payload):
            raise ValueError("Unexpected file in system gateway package: " + normalized)
    for dest, (_, _, sha) in payload.items():
        if extract is None:
            content = subprocess.run(["/usr/bin/bsdtar", "-xOf", str(pkg), dest],
                                     capture_output=True, timeout=30, check=False)
        else:
            content = extract(pkg, dest)
        if content.returncode != 0 or digest(content.stdout) != sha:
            raise ValueError("Built system package does not match trusted gateway bytes: " + dest)
    return pkg


def build_deb_package(root, directory, command=run, extract=None):
    """Build and verify a Debian/Ubuntu .deb gateway package without root or maintainer scripts."""
    payload = expected_files(root)
    path = Path(directory)
    pkgroot = path / "debroot"
    debian_dir = pkgroot / "DEBIAN"
    debian_dir.mkdir(parents=True, exist_ok=True)
    (debian_dir / "control").write_text(DEB_CONTROL, encoding="utf-8")
    for dest, (content, mode, _) in payload.items():
        target = pkgroot / dest
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(content)
        target.chmod(mode)
    for item in debian_dir.iterdir():
        if item.name in DEB_FORBIDDEN_SCRIPTS or item.name != "control":
            raise ValueError("Forbidden Debian maintainer script in gateway build: " + item.name)
    deb_path = path / f"{PACKAGE}_{VERSION}-{RELEASE}_all.deb"
    result = command(["/usr/bin/dpkg-deb", "--root-owner-group", "--build", str(pkgroot), str(deb_path)],
                     cwd=path, timeout=120)
    if result.returncode != 0:
        raise ValueError("dpkg-deb could not build the trusted gateway: " + result.stderr[-MAX_RESULT:])
    listing = command(["/usr/bin/dpkg-deb", "-c", str(deb_path)], timeout=30)
    if listing.returncode != 0:
        raise ValueError("Cannot inspect the newly built Debian gateway package")
    for line in listing.stdout.splitlines():
        parts = line.split()
        if not parts:
            continue
        perms = parts[0]
        if perms.startswith("l"):
            raise ValueError("Symlink entry forbidden in Debian gateway package")
        member = parts[-1].removeprefix("./").rstrip("/")
        if not member:
            continue
        if member not in payload and not any(x.startswith(member + "/") for x in payload):
            raise ValueError("Unexpected file in Debian gateway package: " + member)
    for dest, (_, _, sha) in payload.items():
        if extract is not None:
            content = extract(deb_path, dest)
            if content.returncode != 0 or digest(content.stdout) != sha:
                raise ValueError("Built Debian package does not match trusted gateway bytes: " + dest)
        else:
            tar_proc = subprocess.run(["/usr/bin/dpkg-deb", "--fsys-tarfile", str(deb_path)],
                                      capture_output=True, timeout=30, check=False)
            if tar_proc.returncode != 0:
                raise ValueError("Cannot extract payload stream from Debian gateway package")
            found = None
            with tarfile.open(fileobj=io.BytesIO(tar_proc.stdout), mode="r:*") as archive:
                for member in archive.getmembers():
                    if member.name.removeprefix("./") == dest:
                        if not member.isfile() or member.issym() or member.islnk():
                            raise ValueError("Nonregular member in Debian gateway package: " + dest)
                        stream = archive.extractfile(member)
                        found = stream.read() if stream is not None else None
                        break
            if found is None or digest(found) != sha:
                raise ValueError("Built Debian package does not match trusted gateway bytes: " + dest)
    return deb_path


def build_rpm_package(root, directory, command=run, extract=None):
    """Build and verify a Fedora/openSUSE .rpm gateway package without root or scriptlets."""
    payload = expected_files(root)
    path = Path(directory)
    topdir = path / "rpmbuild"
    for sub in ("BUILD", "RPMS", "SOURCES", "SPECS", "SRPMS"):
        (topdir / sub).mkdir(parents=True, exist_ok=True)
    for dest, (content, mode, _) in payload.items():
        target = topdir / "SOURCES" / Path(dest).name
        target.write_bytes(content)
        target.chmod(mode)
    spec_path = topdir / "SPECS" / f"{PACKAGE}.spec"
    spec_path.write_text(RPM_SPEC, encoding="utf-8")
    result = command(["/usr/bin/rpmbuild", "-bb", "--define", f"_topdir {topdir}", str(spec_path)],
                     cwd=path, timeout=180)
    if result.returncode != 0:
        raise ValueError("rpmbuild could not build the trusted gateway: " + result.stderr[-MAX_RESULT:])
    rpms = list((topdir / "RPMS").rglob(f"{PACKAGE}-{VERSION}-{RELEASE}*.rpm"))
    if len(rpms) != 1:
        raise ValueError("RPM gateway build produced an unexpected package count")
    rpm_path = rpms[0]
    scripts_check = command(["/usr/bin/rpm", "-qp", "--scripts", str(rpm_path)], timeout=30)
    if scripts_check.returncode != 0 or scripts_check.stdout.strip():
        raise ValueError("RPM gateway package contains forbidden scriptlets")
    listing = command(["/usr/bin/rpm", "-qpl", str(rpm_path)], timeout=30)
    if listing.returncode != 0:
        raise ValueError("Cannot inspect the newly built RPM gateway package")
    expected_paths = {"/" + dest for dest in payload}
    listed_paths = {line.strip() for line in listing.stdout.splitlines() if line.strip()}
    if listed_paths != expected_paths:
        raise ValueError("Unexpected file list in RPM gateway package: " + ", ".join(sorted(listed_paths)))
    for dest, (_, _, sha) in payload.items():
        if extract is not None:
            content = extract(rpm_path, dest)
        else:
            cpio_stream = subprocess.run(["/usr/bin/rpm2cpio", str(rpm_path)],
                                         capture_output=True, timeout=30, check=False)
            if cpio_stream.returncode != 0:
                raise ValueError("Cannot read cpio stream from RPM gateway package")
            content = subprocess.run(
                ["/usr/bin/cpio", "-i", "--to-stdout", "--quiet", f"./{dest}"],
                input=cpio_stream.stdout, capture_output=True, timeout=30, check=False)
            if content.returncode != 0 or not content.stdout:
                content = subprocess.run(
                    ["/usr/bin/cpio", "-i", "--to-stdout", "--quiet", dest],
                    input=cpio_stream.stdout, capture_output=True, timeout=30, check=False)
        if content.returncode != 0 or digest(content.stdout) != sha:
            raise ValueError("Built RPM package does not match trusted gateway bytes: " + dest)
    return rpm_path


def build_distro_package(distro, root, directory, command=run, extract=None):
    if distro == "arch":
        return build_package(root, directory, command=command, extract=extract)
    if distro == "debian":
        return build_deb_package(root, directory, command=command, extract=extract)
    if distro in ("fedora", "opensuse"):
        return build_rpm_package(root, directory, command=command, extract=extract)
    raise ValueError(f"Unsupported distribution for gateway build: {distro}")


def _privilege_install_argv(distro, package_path):
    if distro == "arch":
        return ["/usr/bin/pkexec", "/usr/bin/pacman", "-U", "--noconfirm", "--", str(package_path)]
    if distro == "debian":
        return ["/usr/bin/pkexec", "/usr/bin/dpkg", "--install", "--", str(package_path)]
    if distro in ("fedora", "opensuse"):
        return ["/usr/bin/pkexec", "/usr/bin/rpm", "-Uvh", "--", str(package_path)]
    raise ValueError(f"Unsupported distribution for gateway installation: {distro}")


def _privilege_remove_argv(distro, pkg_name):
    if distro == "arch":
        return ["/usr/bin/pkexec", "/usr/bin/pacman", "-R", "--noconfirm", pkg_name]
    if distro == "debian":
        return ["/usr/bin/pkexec", "/usr/bin/dpkg", "--remove", pkg_name]
    if distro in ("fedora", "opensuse"):
        return ["/usr/bin/pkexec", "/usr/bin/rpm", "-e", pkg_name]
    raise ValueError(f"Unsupported distribution for gateway removal: {distro}")


def _check_required_tools(distro, fs_root=Path("/")):
    spec = SUPPORTED_DISTROS.get(distro)
    if not spec:
        raise ValueError(f"Unsupported distribution for system gateway: {distro}")
    for tool in spec["requiredTools"]:
        candidate = fs_root / tool.lstrip("/") if fs_root != Path("/") else Path(tool)
        if not candidate.is_file() or not os.access(candidate, os.X_OK):
            label = "Arch" if distro == "arch" else distro.capitalize()
            raise ValueError(f"Required {label} system-package tool missing: {tool}")


def install(root=ROOT, command=run, *, distro=None, fs_root=Path("/"), extract=None):
    if os.geteuid() == 0:
        raise ValueError("Gateway package builds must run as an unprivileged user")
    if distro is None:
        detected = detect_distro(fs_root)
        if not detected["supported"]:
            raise ValueError(detected["reason"])
        distro = detected["family"]
    elif distro not in SUPPORTED_DISTROS:
        detected = detect_distro(fs_root)
        if not detected["supported"] and detected["family"] == distro:
            raise ValueError(detected["reason"])
        raise ValueError(f"Unsupported distribution '{distro}' for system gateway")

    _check_required_tools(distro, fs_root=fs_root)
    checker = lambda pkg: installed(pkg, distro=distro, command=command)
    if any(checker(shell_pkg) for shell_pkg in SHELL_PACKAGES):
        label = "Arch" if distro == "arch" else distro.capitalize()
        raise ValueError(f"{label} shell package already owns this gateway; upgrade the shell package instead")
    state = system_state(fs_root, checker, distro=distro, command=command)
    if state["installed"]:
        return {"ok": True, **state, "message": "System gateway package is already installed"}
    if state["packageInstalled"]:
        raise ValueError("Existing managed system gateway is modified; refusing overwrite")
    for dest, _, _ in FILES.values():
        target = fs_root / dest
        if target.exists() or target.is_symlink():
            raise ValueError("A different installation already owns: /" + dest)
    with tempfile.TemporaryDirectory(prefix="alis-integration-gateway-") as folder:
        package = build_distro_package(distro, root, folder, command=command, extract=extract)
        # This is the ONLY privileged action. Package contains no maintainer
        # scripts, no arbitrary files, and has been verified against two SHA-256 pins.
        result = command(_privilege_install_argv(distro, package), timeout=120)
        if result.returncode != 0:
            raise ValueError("Gateway installation cancelled or failed: " + result.stderr[-MAX_RESULT:])
    state = system_state(fs_root, checker, distro=distro, command=command)
    if not state["installed"]:
        # Roll back unverified partial package registration if the package manager
        # recorded ownership without matching verified files on disk.
        if state["packageInstalled"]:
            command(_privilege_remove_argv(distro, PACKAGE), timeout=120)
        raise ValueError("System package operation returned without a verified installed gateway")
    return {"ok": True, **state, "message": "Trusted system gateway installed; hardware helpers remain opt-in"}


def remove(command=run, *, distro=None, fs_root=Path("/")):
    if distro is None:
        detected = detect_distro(fs_root)
        if not detected["supported"]:
            raise ValueError(detected["reason"])
        distro = detected["family"]
    elif distro not in SUPPORTED_DISTROS:
        raise ValueError(f"Unsupported distribution '{distro}' for system gateway removal")

    checker = lambda pkg: installed(pkg, distro=distro, command=command)
    pkg = PACKAGE if checker(PACKAGE) else (LEGACY_PACKAGE if checker(LEGACY_PACKAGE) else "")
    current_state = system_state(fs_root, checker, distro=distro, command=command)
    if not pkg:
        return {"ok": True, **current_state, "message": "Standalone gateway package was not installed"}
    if current_state["diagnostic"] == "modified":
        raise ValueError("Managed system gateway files were modified; refusing removal to preserve administrator changes")
    # Never remove the gateway while its owned helper files might still be in use.
    provisioner = fs_root / "usr/libexec/alis-intergration-system-provision"
    if pkg == LEGACY_PACKAGE and not provisioner.is_file():
        provisioner = fs_root / LEGACY_FILES[0][0]
    status = command([str(provisioner), "status"], timeout=12)
    try:
        current = json.loads(status.stdout.strip())
    except ValueError:
        raise ValueError("Cannot inspect system helper state; preserving gateway package")
    if status.returncode != 0 or current.get("installed") or current.get("managed"):
        raise ValueError("Remove managed TLP/Thinkfan helpers first; preserving gateway package")
    response = command(_privilege_remove_argv(distro, pkg), timeout=120)
    if response.returncode != 0:
        raise ValueError("Gateway removal cancelled or failed: " + response.stderr[-MAX_RESULT:])
    post_state = system_state(fs_root, checker, distro=distro, command=command)
    if post_state["packageInstalled"]:
        raise ValueError("Gateway package removal was not confirmed by the package database")
    return {"ok": True, **post_state, "message": "Standalone system gateway package removed"}


def rollback(root=ROOT, command=run, *, distro=None, fs_root=Path("/"), extract=None):
    """Restore a clean verified gateway state or remove an unverified standalone gateway."""
    if distro is None:
        detected = detect_distro(fs_root)
        if not detected["supported"]:
            raise ValueError(detected["reason"])
        distro = detected["family"]
    checker = lambda pkg: installed(pkg, distro=distro, command=command)
    current = system_state(fs_root, checker, distro=distro, command=command)
    if current["installed"]:
        return {"ok": True, **current, "message": "System gateway already verified"}
    if current["packageInstalled"]:
        for dest, _, _ in FILES.values():
            target = fs_root / dest
            if target.is_symlink():
                raise ValueError("Refusing rollback with symlinked gateway destination: /" + dest)
        return remove(command=command, distro=distro, fs_root=fs_root)
    return install(root=root, command=command, distro=distro, fs_root=fs_root, extract=extract)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("action", choices=("status", "install", "remove", "rollback"))
    parser.add_argument("--distro", default=None, help="Optional explicit distribution family override for testing")
    args = parser.parse_args()
    try:
        if args.action == "status":
            result = {"ok": True, **system_state(distro=args.distro)}
        elif args.action == "install":
            result = install(distro=args.distro)
        elif args.action == "remove":
            result = remove(distro=args.distro)
        else:
            result = rollback(distro=args.distro)
        print(json.dumps(result))
    except (OSError, ValueError, TypeError, subprocess.SubprocessError) as error:
        print(json.dumps({"ok": False, "error": str(error)}))
        raise SystemExit(1)


if __name__ == "__main__":
    main()
