import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const p=vm.createContext({Date,Math,Number,JSON});
vm.runInContext(fs.readFileSync(new URL('../services/AgendaTodoPolicy.js',import.meta.url),'utf8'),p);
let checks=0;
function check(ok,label){checks++;assert.ok(ok,label);}
const link=p.newLink(42,1720000000000,'abc123');
check(p.validLink(link),'new creation has a valid stable key');
for(const bad of [null,{}, {...link,version:2},{...link,key:'../bad'},{...link,state:'done'}])check(!p.validLink(bad),'foreign/unversioned metadata is not eligible');
const event={id:42,title:'Planning\nmeeting',description:'Agenda detail',dateTime:'2099-01-03T10:15:00Z',endDate:'2099-01-03T11:00:00Z',todoLink:link};
const task=p.linkedItem(event,null);
check(task.content==='Planning meeting'&&!task.done,'one ordinary unchecked task');
check(task.id==='agenda:'+link.key&&task.agenda.key===link.key,'persisted identity excludes mutable title/time');
const edited=p.linkedItem({...event,title:'Changed title',description:'Changed detail',allDay:true},{...task,done:true,notes:'Independent\nnotes'});
check(edited.id===task.id&&edited.done&&edited.notes==='Independent\nnotes','completion/notes and identity survive editing');
check(edited.startTime===''&&edited.endTime===''&&edited.content==='Changed title','all-day owns only event fields');
check(p.fingerprint(event)===task.agenda.fingerprint,'durable comparison includes the event data');
check(p.fingerprint({...event,notified:true,reminderNotified:true})===p.fingerprint(event),'alarms do not mutate linked tasks');
check(p.fingerprint({...event,description:'new'})!==p.fingerprint(event),'details updates are acknowledged');
check(p.linkedItem({...event,dateTime:'invalid',endDate:'invalid'},null).date==='','malformed legacy dates are bounded');
for(let id=1;id<=128;id++)check(p.newLink(id,1720000000000,'same').key!==link.key || id===42,'occurrence identity includes its numeric event identity');
console.log('AGENDA_TODO_POLICY_PASS',checks);
